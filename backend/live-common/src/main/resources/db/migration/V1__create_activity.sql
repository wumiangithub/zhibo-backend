CREATE TABLE activity (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  provider VARCHAR(32) NOT NULL,
  provider_room_id VARCHAR(64) NULL,
  title VARCHAR(64) NOT NULL,
  introduction VARCHAR(256) NULL,
  start_time VARCHAR(32) NOT NULL,
  end_time VARCHAR(32) NULL,
  type INT NOT NULL,
  state INT NOT NULL DEFAULT 2,
  viewer_style VARCHAR(32) NULL,
  ultra_low_latency BOOLEAN NULL,
  virtual_avatar BOOLEAN NULL,
  cover_url VARCHAR(1024) NULL,
  warmup_type VARCHAR(16) NULL,
  warmup_url VARCHAR(1024) NULL,
  promo_cover_url VARCHAR(1024) NULL,
  detail_html MEDIUMTEXT NULL,
  share_link VARCHAR(1024) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY idx_activity_provider (provider),
  KEY idx_activity_state (state),
  KEY idx_activity_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
